/**
 * SMART AUTO SELECT BEST XI ENGINE (10-Factor Tactical Evaluator)
 * Evaluates Match Format, Pitch Condition, Opponent Strength, Form, Fitness,
 * Role Specialization, Batting/Bowling Balance, Spin/Pace Ratio, Overseas Quota, and Injuries.
 */
export function smartAutoSelectBestXI(params: {
  squadPlayers: RealCricketer[];
  format: MatchFormat;
  pitch: LiveMatchState['pitchCondition'];
  mode: CompetitionMode;
  opponentReputation: number;
  currentCaptainId: string;
}): {
  playingXIIds: string[];
  captainId: string;
  viceCaptainId: string;
  wicketkeeperId: string;
  bowlingOptionsIds: string[];
  explanations: string[];
} {
  const { squadPlayers, format, pitch, mode, opponentReputation, currentCaptainId } = params;
  const maxOverseas = mode === 'FRANCHISE_T20' ? 4 : 11;
  const explanations: string[] = [];

  const isSpinTrack = pitch === 'Dry Spinning Deck';
  const isPaceTrack = pitch === 'Green Seam Surface';
  const targetSpinners = isSpinTrack ? 3 : 2;
  const targetPacers = isPaceTrack ? 3 : 2;

  const isSpinner = (p: RealCricketer) =>
    p.role === 'Spin Bowler' ||
    p.bowlingStyle.toLowerCase().includes('orth') ||
    p.bowlingStyle.toLowerCase().includes('legbreak') ||
    p.bowlingStyle.toLowerCase().includes('offbreak');

  const isPacer = (p: RealCricketer) =>
    p.role === 'Fast Bowler' || p.bowlingStyle.toLowerCase().includes('fast');

  // Score each player holistically (not just raw OVR)
  const scored = squadPlayers.map((p) => {
    let score = p.gameAttributes.ovr * 1.0;
    // Form & Fitness weighting
    score += (p.gameAttributes.form - 80) * 0.45;
    score += (p.gameAttributes.fitness - 85) * 0.35;
    if (p.injuryStatus !== 'FIT') score -= 25;

    // Format specialization
    if (format === 'T20') {
      score += (p.verifiedStats.strikeRate - 130) * 0.18;
      score += p.gameAttributes.deathBowling * 0.08;
    } else if (format === 'Test') {
      score += (p.verifiedStats.battingAvg - 30) * 0.32;
      score += p.gameAttributes.control * 0.15;
    } else {
      score += (p.verifiedStats.battingAvg - 28) * 0.22;
    }

    // Pitch condition weighting
    if (isSpinTrack && isSpinner(p)) score += 6.5;
    if (isPaceTrack && isPacer(p)) score += 6.5;
    if (pitch === 'Hard Batting Track' && p.gameAttributes.battingPower >= 88) score += 4.5;

    return { player: p, tacticalScore: score };
  });

  scored.sort((a, b) => b.tacticalScore - a.tacticalScore);

  const omittedLowFitness = scored.find((s) => s.player.gameAttributes.fitness < 87 || s.player.injuryStatus !== 'FIT');

  const selected: RealCricketer[] = [];
  let overseasCount = 0;

  const canAdd = (p: RealCricketer) => {
    if (selected.some((s) => s.id === p.id)) return false;
    if (p.isOverseasInIPL && overseasCount >= maxOverseas) return false;
    return true;
  };

  const addPlayer = (p: RealCricketer) => {
    selected.push(p);
    if (p.isOverseasInIPL) overseasCount++;
  };

  // 1. Select best Wicketkeeper
  const wks = scored.filter((s) => s.player.role === 'Wicketkeeper' && canAdd(s.player));
  if (wks.length > 0) {
    addPlayer(wks[0].player);
    explanations.push(`Suitable wicketkeeper selected: ${wks[0].player.fullName} (Form ${wks[0].player.gameAttributes.form}).`);
  }

  // 2. Select required Spinners for pitch
  const spinners = scored.filter((s) => isSpinner(s.player) && canAdd(s.player));
  for (const sp of spinners.slice(0, targetSpinners)) {
    if (canAdd(sp.player)) addPlayer(sp.player);
  }

  // 3. Select required Fast Bowlers for pitch
  const pacers = scored.filter((s) => isPacer(s.player) && canAdd(s.player));
  for (const pc of pacers.slice(0, targetPacers)) {
    if (canAdd(pc.player)) addPlayer(pc.player);
  }

  // 4. Fill remaining slots with top All-Rounders & specialist Batsmen
  for (const item of scored) {
    if (selected.length >= 11) break;
    if (canAdd(item.player)) {
      addPlayer(item.player);
    }
  }

  // Fallback if overseas cap prevented 11
  for (const item of scored) {
    if (selected.length >= 11) break;
    if (!selected.some((s) => s.id === item.player.id)) {
      addPlayer(item.player);
    }
  }

  // Arrange optimal batting order (Openers/Top order -> Middle -> All-Rounders -> Bowlers)
  const orderWeight = (p: RealCricketer) => {
    if (p.tacticalInstruction.preferredBattingPhase === 'Powerplay') return 1;
    if (p.tacticalInstruction.preferredBattingPhase === 'Anchor') return 2;
    if (p.role === 'Batsman' || p.role === 'Wicketkeeper') return 3;
    if (p.role === 'All-Rounder') return 4;
    return 5;
  };

  selected.sort((a, b) => {
    const wDiff = orderWeight(a) - orderWeight(b);
    if (wDiff !== 0) return wDiff;
    return b.gameAttributes.battingTiming - a.gameAttributes.battingTiming;
  });

  const playingXIIds = selected.map((p) => p.id);
  const wkId = selected.find((p) => p.role === 'Wicketkeeper')?.id || playingXIIds[0];
  const captId = playingXIIds.includes(currentCaptainId) ? currentCaptainId : playingXIIds[0];
  const viceCaptId = playingXIIds.find((id) => id !== captId) || playingXIIds[0];

  const bowlingOptionsIds = selected
    .filter(
      (p) =>
        p.role === 'Fast Bowler' ||
        p.role === 'Spin Bowler' ||
        p.role === 'All-Rounder'
    )
    .map((p) => p.id);

  explanations.unshift(
    `Best ${format} batting combination arranged from #1 ${selected[0]?.fullName} to finisher ${selected[5]?.fullName}.`
  );
  if (isSpinTrack) {
    explanations.push(`Strongest spin-focused attack deployed for ${pitch} (${targetSpinners} spin options).`);
  } else if (isPaceTrack) {
    explanations.push(`Extra seam & new-ball pace attack selected for ${pitch}.`);
  } else {
    explanations.push(`Balanced pace and spin bowling unit calibrated against Opponent Rep ${opponentReputation}.`);
  }
  if (omittedLowFitness && !playingXIIds.includes(omittedLowFitness.player.id)) {
    explanations.push(
      `${omittedLowFitness.player.fullName} rested/omitted due to lower fitness reserve (${omittedLowFitness.player.gameAttributes.fitness}%).`
    );
  } else {
    explanations.push(`Overseas quota verified (${overseasCount}/${maxOverseas} overseas slots used).`);
  }

  return {
    playingXIIds,
    captainId: captId,
    viceCaptainId: viceCaptId,
    wicketkeeperId: wkId,
    bowlingOptionsIds: bowlingOptionsIds.length >= 5 ? bowlingOptionsIds : playingXIIds.slice(-5),
    explanations,
  };
}

