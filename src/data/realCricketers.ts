/**
 * DOCUMENTED GAME RATING FORMULA
 * Computes in-game tactical attributes (OVR, Batting Power, Timing, Bowling Skill, Control, Variations, Fielding)
 * strictly from verified career batting averages, strike rates, bowling economies, and international caps.
 * Clearly identified in UI as Game-Calculated Attributes.
 */
export function calculateGameAttributes(
  role: PlayerRole,
  stats: VerifiedCareerStats,
  age: number,
  basePriceCr: number,
  estimatedValueCr: number
): CalculatedGameAttributes {
  const batFactor = Math.min(98, Math.round(52 + (stats.battingAvg - 18) * 0.95 + (stats.strikeRate - 115) * 0.42));
  const powerRaw = Math.min(98, Math.round(50 + (stats.strikeRate - 110) * 0.78 + stats.hundreds * 1.5));
  const timingRaw = Math.min(98, Math.round(55 + (stats.battingAvg - 15) * 1.15 + stats.fifties * 0.28));

  const econ = stats.economy ?? 8.8;
  const bowlAvg = stats.bowlingAvg ?? 32;
  const bowlRaw =
    stats.wickets > 15
      ? Math.min(98, Math.round(62 + (9.2 - econ) * 11 + (30 - bowlAvg) * 0.9 + Math.min(10, stats.wickets / 35)))
      : 42;

  const controlRaw =
    stats.wickets > 15
      ? Math.min(98, Math.round(65 + (9.0 - econ) * 12.5))
      : 45;

  const variationsRaw =
    stats.wickets > 15
      ? Math.min(97, Math.round(64 + (32 - bowlAvg) * 1.2 + Math.min(12, stats.wickets / 25)))
      : 44;

  let ovr = 82;
  if (role === 'Batsman' || role === 'Wicketkeeper') {
    ovr = Math.round(timingRaw * 0.52 + powerRaw * 0.38 + Math.min(95, 75 + stats.internationalCaps * 0.08) * 0.1);
  } else if (role === 'Fast Bowler' || role === 'Spin Bowler') {
    ovr = Math.round(bowlRaw * 0.5 + controlRaw * 0.3 + variationsRaw * 0.2);
  } else {
    ovr = Math.round(Math.max(batFactor, bowlRaw) * 0.55 + Math.min(batFactor, bowlRaw) * 0.35 + 10);
  }

  ovr = Math.max(78, Math.min(97, ovr));
  const potential = age <= 24 ? Math.min(98, ovr + 5) : age <= 28 ? Math.min(97, ovr + 2) : ovr;

  return {
    ovr,
    potential,
    battingPower: Math.max(40, Math.min(98, powerRaw)),
    battingTiming: Math.max(42, Math.min(98, timingRaw)),
    paceVsSpin: Math.max(60, Math.min(97, Math.round((powerRaw + timingRaw) / 2))),
    bowlingSkill: Math.max(35, Math.min(98, bowlRaw)),
    control: Math.max(38, Math.min(98, controlRaw)),
    variations: Math.max(38, Math.min(98, variationsRaw)),
    deathBowling: Math.max(35, Math.min(98, Math.round(controlRaw * 0.6 + variationsRaw * 0.4))),
    fieldingReflexes: Math.max(72, Math.min(97, Math.round(76 + (stats.catches / Math.max(1, stats.matches)) * 22))),
    fitness: age <= 29 ? 94 : age <= 34 ? 90 : 86,
    form: Math.min(96, Math.max(76, ovr - 2)),
    morale: 88,
    basePriceCr,
    estimatedValueCr,
    contractSalaryCr: estimatedValueCr,
  };
}

